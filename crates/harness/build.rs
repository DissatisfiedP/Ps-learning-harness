//! Bundles `prompts/**/*.md` into the binary as a `path -> &'static str` map.
//!
//! A build script (rather than `include_dir`) keeps the dependency surface at
//! zero. The generated table is compiled into the crate; learner overrides are
//! looked up at runtime in `<repo>/prompts/<same relative path>`.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let prompts = manifest.join("prompts");
    println!("cargo:rerun-if-changed={}", prompts.display());

    let mut files: Vec<String> = Vec::new();
    collect(&prompts, &prompts, &mut files);
    files.sort();

    let mut out = String::from(
        "// @generated by build.rs. Do not edit.\n\
         pub static PROMPTS: &[(&str, &str)] = &[\n",
    );
    for rel in &files {
        // Paths use forward slashes so the table is platform-independent.
        out.push_str(&format!(
            "    (\"{rel}\", include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/prompts/{rel}\"))),\n"
        ));
    }
    out.push_str("];\n");

    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("prompt_files.rs");
    fs::write(&dest, out).unwrap();
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    let entries = match fs::read_dir(dir) {
        Ok(e) => e,
        Err(_) => return,
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if path.extension().is_some_and(|e| e == "md") {
            let rel = path
                .strip_prefix(root)
                .unwrap()
                .to_string_lossy()
                .replace('\\', "/");
            out.push(rel);
            println!("cargo:rerun-if-changed={}", path.display());
        }
    }
}
