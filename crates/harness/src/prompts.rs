//! Prompt composer (architecture §4.10, §4.15; `prompts/README.md`).
//!
//! Responsibilities:
//! - bundle every `prompts/**/*.md` (generated table from `build.rs`);
//! - let a learner override at `<repo>/prompts/<same path>` win when non-empty;
//! - render the tiny template language (`{{name}}`, `{{a.b}}`, `{{#flag}}…`);
//! - parse plugin YAML-ish frontmatter into a manifest, keeping only the body;
//! - compose the tutor / planner / researcher / compaction system prompts;
//! - render `session_state` as compact Markdown.
//!
//! Every placeholder must be supplied: a missing value is an error, so prompt
//! and code drift fails loudly rather than silently producing a weak prompt.

use std::collections::{HashMap, HashSet};
use std::path::{Path, PathBuf};

use crate::state::SessionState;
use crate::Error;

// Generated by build.rs: `static PROMPTS: &[(&str, &str)]`.
include!(concat!(env!("OUT_DIR"), "/prompt_files.rs"));

/// Values for `{{name}}` / `{{a.b}}` placeholders. Dotted keys are stored as
/// their literal dotted string (e.g. `"section.title"`).
#[derive(Debug, Clone, Default)]
pub struct TemplateValues(HashMap<String, String>);

impl TemplateValues {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn set(&mut self, key: impl Into<String>, value: impl Into<String>) -> &mut Self {
        self.0.insert(key.into(), value.into());
        self
    }

    pub fn get(&self, key: &str) -> Option<&str> {
        self.0.get(key).map(String::as_str)
    }
}

/// A venue read out of the scope brief's `venues` (docs/learning-system.md
/// §6). Parsed defensively: briefs are model output.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Venue {
    /// ask | discussion | reference
    pub kind: String,
    pub name: String,
    /// What the learner must hold for it to be useful; empty when the brief
    /// didn't say.
    pub entry_level: String,
}

pub struct Composer {
    repo: PathBuf,
}

impl Composer {
    pub fn new(repo: &Path) -> Self {
        Self {
            repo: repo.to_owned(),
        }
    }

    /// The brief's venues, in the order the brief listed them. Unknown fields
    /// are ignored and an entry without a kind or a name is dropped, so a
    /// malformed brief yields fewer lines rather than a failure.
    pub fn brief_venues(brief: Option<&serde_json::Value>) -> Vec<Venue> {
        let Some(list) = brief
            .and_then(|b| b.get("venues"))
            .and_then(|v| v.as_array())
        else {
            return Vec::new();
        };
        list.iter()
            .filter_map(|v| {
                let field = |key: &str| {
                    v.get(key)
                        .and_then(serde_json::Value::as_str)
                        .map(str::trim)
                        .filter(|s| !s.is_empty())
                };
                Some(Venue {
                    kind: field("kind")?.to_owned(),
                    name: field("name")?.to_owned(),
                    entry_level: field("entryLevel").unwrap_or("").to_owned(),
                })
            })
            .collect()
    }

    /// Bundled text for a prompt path, or `None` when the path isn't bundled.
    pub fn bundled(path: &str) -> Option<&'static str> {
        PROMPTS
            .iter()
            .find(|(p, _)| *p == path)
            .map(|(_, text)| *text)
    }

    /// Learner override wins when it exists and is non-empty; otherwise the
    /// bundled copy. A missing bundled path is an error (drift fails loudly).
    pub fn load(&self, path: &str) -> Result<String, Error> {
        let override_path = self.repo.join("prompts").join(path);
        match std::fs::read_to_string(&override_path) {
            Ok(text) if !text.trim().is_empty() => return Ok(text),
            Ok(_) => {} // empty override: fall back to bundled
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
            Err(e) => return Err(e.into()),
        }
        Self::bundled(path)
            .map(str::to_owned)
            .ok_or_else(|| Error::Prompt(format!("no bundled prompt for {path}")))
    }

    /// Catalog text for the planner/researcher, filtered by platform. With
    /// nothing registered the catalog empty (callers render "none available").
    pub fn plugin_catalog(
        &self,
        platform: &str,
        manifests: &[crate::plugins::PluginManifest],
    ) -> String {
        let lines: Vec<String> = manifests
            .iter()
            .filter(|m| m.platforms.iter().any(|p| p == platform))
            .map(crate::plugins::PluginManifest::catalog_line)
            .collect();
        if lines.is_empty() {
            "none available".to_owned()
        } else {
            lines.join("\n")
        }
    }

    // ---- composition ----------------------------------------------------

    /// Tutor system prompt: shared fragments → base → phase instructions.
    /// `phase_values` supplies the phase file's placeholders (section fields,
    /// mode, active_plugins); `base_values` supplies session_state/phase.
    pub fn compose_tutor(
        &self,
        phase_file: &str,
        phase_label: &str,
        base_values: &TemplateValues,
        phase_values: &TemplateValues,
        flags: &HashSet<String>,
    ) -> Result<String, Error> {
        let mut shared = vec![
            "shared/voice.md",
            "shared/accuracy.md",
            "shared/learner-signals.md",
            "shared/questions.md",
            "shared/formatting.md",
            "shared/learner-files.md",
        ];
        if flags.contains("workspace") {
            shared.push("shared/workspace.md");
        }
        let mut parts = Vec::with_capacity(shared.len() + 1);
        for p in shared {
            parts.push(self.load(p)?);
        }
        let base = self.load("tutor/base.md")?;
        parts.push(base);

        // Render the phase file first (its own placeholders), then supply it
        // as `phase_instructions` to the base render.
        let phase_text = render(&self.load(phase_file)?, phase_values, flags)?;
        let mut vals = base_values.clone();
        vals.set("phase", phase_label);
        vals.set("phase_instructions", phase_text);
        render(&parts.join("\n\n"), &vals, flags)
    }

    /// Planner system prompt: its shared fragments → base → exam_mode.
    pub fn compose_planner(
        &self,
        values: &TemplateValues,
        exam_mode: Option<&str>,
        flags: &HashSet<String>,
    ) -> Result<String, Error> {
        let shared = [
            "shared/accuracy.md",
            "shared/learner-signals.md",
            "shared/learner-files.md",
        ];
        let mut parts = Vec::with_capacity(shared.len() + 2);
        for p in shared {
            parts.push(self.load(p)?);
        }
        parts.push(self.load("planner/base.md")?);
        let exam = match exam_mode {
            Some("exam") => render(&self.load("planner/exam.md")?, values, flags)?,
            _ => String::new(),
        };
        let mut vals = values.clone();
        vals.set("exam_mode", exam);
        // exam.md placeholders are supplied through `values` when present.
        render(&parts.join("\n\n"), &vals, flags)
    }

    /// A job's system prompt (e.g. `jobs/researcher.md`), with all its
    /// placeholders supplied through `values`.
    pub fn compose_job(
        &self,
        path: &str,
        values: &TemplateValues,
        flags: &HashSet<String>,
    ) -> Result<String, Error> {
        render(&self.load(path)?, values, flags)
    }

    /// Compaction turn instruction.
    pub fn compose_compaction(
        &self,
        values: &TemplateValues,
        flags: &HashSet<String>,
    ) -> Result<String, Error> {
        render(&self.load("compaction.md")?, values, flags)
    }

    /// The Practice system prompt. Practice has no tools, so no flag is set
    /// (its `{{#workspace}}` line is for when `workspace_write` reaches it).
    pub fn compose_practice(&self) -> Result<String, Error> {
        render(
            &self.load("practice.md")?,
            &TemplateValues::new(),
            &HashSet::new(),
        )
    }

    /// Compact Markdown view of the pinned session state (architecture §4.15).
    /// Kept small; full detail lives in the transcript.
    pub fn session_state(state: &SessionState) -> String {
        Self::session_state_with(state, None)
    }

    /// As [`Self::session_state`], showing the device's saved starting point
    /// (§3) until a goal record exists: the measure-phase tutor needs it to
    /// decide whether to ask, and once `goal_set` runs the goal JSON carries
    /// it. `None` renders exactly what an older session rendered.
    pub fn session_state_with(
        state: &SessionState,
        starting_point_default: Option<&str>,
    ) -> String {
        let mut out = String::new();
        out.push_str("## Goal\n");
        match (state.goal.as_ref(), starting_point_default) {
            (None, Some(point)) => {
                out.push_str(&format!("(none yet) · saved starting point: {point}"))
            }
            _ => out.push_str(&compact_value(state.goal.as_ref())),
        }
        out.push_str("\n\n## Field brief\n");
        out.push_str(&compact_value(state.brief.as_ref()));
        out.push_str("\n\n## Probe map\n");
        if state.probe.is_empty() {
            out.push_str("(none yet)");
        } else {
            for p in &state.probe {
                out.push_str("- ");
                out.push_str(&compact_value(Some(p)));
                out.push('\n');
            }
        }
        out.push_str("\n## Plan");
        match &state.plan {
            None => out.push_str("\n(no plan yet)\n"),
            Some(plan) => {
                out.push_str(&format!(" (v{})\n", plan.version));
                out.push_str(&truncate(&plan.approach, 400));
                out.push('\n');
                // The learner's plan-level settings (§4), on one line so the
                // planner can re-derive defaults without overriding an
                // explicit choice. Empty in an older session: the line is
                // dropped whole, so its text is unchanged.
                let mut settings = Vec::new();
                if !plan.depth.is_empty() {
                    settings.push(format!("depth: {}", plan.depth));
                }
                if !plan.explore.is_empty() {
                    settings.push(format!("explore: {}", plan.explore));
                }
                if let Some(minutes) = plan.minutes_per_sitting {
                    settings.push(format!("sitting: {minutes} min"));
                }
                if !plan.style.is_empty() {
                    settings.push(format!("style: {}", plan.style));
                }
                if !settings.is_empty() {
                    out.push_str(&settings.join(" · "));
                    out.push('\n');
                }
                for s in &plan.sections {
                    let mark = if state.current_section.as_deref() == Some(s.id.as_str()) {
                        "▶ "
                    } else {
                        ""
                    };
                    out.push_str(&format!(
                        "- {}{} [{}] nodes: {}",
                        mark,
                        s.id,
                        s.mode.as_str(),
                        s.node_ids.join(", ")
                    ));
                    // How far the section goes (§2) and that the learner
                    // claims the material (§4).
                    if let Some(level) = s.target_level {
                        out.push_str(&format!(" · aim: {}", level.as_str()));
                    }
                    if s.assumed_known && !state.known_refuted.contains(&s.id) {
                        out.push_str(" · known");
                    }
                    // The hunt's lifecycle (§5): `ready` until the tutor sends
                    // it, then `out`, `returned` or `skipped`. Only the
                    // current section has one, and only while it is live.
                    if state.current_section.as_deref() == Some(s.id.as_str()) {
                        let hunt = state.hunt_state();
                        if !hunt.is_empty() {
                            out.push_str(&format!(" · hunt: {hunt}"));
                        }
                    }
                    out.push('\n');
                }
            }
        }
        // Where the field lives (§6). Only `ask` venues survive a `pass`
        // depth: the learner wants to finish, not to read around.
        let depth = state.plan.as_ref().map_or("", |p| p.depth.as_str());
        let venues: Vec<Venue> = Composer::brief_venues(state.brief.as_ref())
            .into_iter()
            .filter(|v| depth != "pass" || v.kind == "ask")
            .collect();
        if !venues.is_empty() {
            out.push_str("\n## Field guide\n");
            for v in &venues {
                if v.kind == "ask" {
                    out.push_str(&format!("- ask  {} — useful now", v.name));
                    if !v.entry_level.is_empty() {
                        out.push_str(&format!("; entry: {}", v.entry_level));
                    }
                } else if v.entry_level.is_empty() {
                    out.push_str(&format!(
                        "- {}  {} — useful once you hold the basics",
                        v.kind, v.name
                    ));
                } else {
                    out.push_str(&format!(
                        "- {}  {} — useful once you hold: {}",
                        v.kind, v.name, v.entry_level
                    ));
                }
                out.push('\n');
            }
        }
        out.push_str("\n## Platform\n");
        out.push_str(if state.platform.is_empty() {
            "desktop"
        } else {
            &state.platform
        });
        out.push_str("\n\n## Learner state\n");
        out.push_str(if state.learner_state.is_empty() {
            "no graph yet"
        } else {
            &state.learner_state
        });
        out.push('\n');
        // How well confidence matched results (§7). Present only when the
        // thresholds are met; the prompter uses these lines verbatim.
        if let Some(c) = &state.calibration {
            out.push_str("\n## Calibration\n");
            for b in &c.buckets {
                out.push_str(&format!(
                    "- {}: {}/{} correct ({}%)\n",
                    b.label,
                    b.correct,
                    b.total,
                    b.percent()
                ));
            }
            for note in &c.notes {
                out.push_str(note);
                out.push('\n');
            }
        }
        out
    }
}

/// Render the template language. Missing placeholder = error. `{{#flag}}`
/// blocks are kept only when the flag is set. Values are inserted verbatim (so
/// callers must pre-render any fragment that itself contains placeholders).
pub fn render(
    template: &str,
    values: &TemplateValues,
    flags: &HashSet<String>,
) -> Result<String, Error> {
    let mut out = String::with_capacity(template.len());
    let mut rest = template;
    while let Some(start) = rest.find("{{") {
        out.push_str(&rest[..start]);
        let after = &rest[start + 2..];
        let Some(end) = after.find("}}") else {
            return Err(Error::Prompt("unterminated {{ placeholder".into()));
        };
        let token = &after[..end];
        let tail = &after[end + 2..];
        if let Some(flag) = token.strip_prefix('#') {
            // Conditional block: find the matching close marker.
            let close = format!("{{{{/{flag}}}}}");
            let Some(close_pos) = tail.find(&close) else {
                return Err(Error::Prompt(format!("unclosed {{{{#{flag}}}}} block")));
            };
            let inner = &tail[..close_pos];
            if flags.contains(flag) {
                out.push_str(&render(inner, values, flags)?);
            }
            rest = &tail[close_pos + close.len()..];
        } else if token.starts_with('/') {
            return Err(Error::Prompt(format!("unexpected {{{{{token}}}}}")));
        } else {
            let value = values.get(token).ok_or_else(|| {
                Error::Prompt(format!("missing placeholder value for {{{{{token}}}}}"))
            })?;
            out.push_str(value);
            rest = tail;
        }
    }
    out.push_str(rest);
    // A leftover `{{` in a value is still a leftover; fail loudly.
    if out.contains("{{") {
        return Err(Error::Prompt(
            "unresolved {{ placeholder after render".into(),
        ));
    }
    Ok(out)
}

fn compact_value(v: Option<&serde_json::Value>) -> String {
    match v {
        None => "(none yet)".to_owned(),
        Some(v) => truncate(&v.to_string(), 600),
    }
}

fn truncate(s: &str, max: usize) -> String {
    match s.char_indices().nth(max) {
        Some((i, _)) => format!("{}…", &s[..i]),
        None => s.to_owned(),
    }
}

